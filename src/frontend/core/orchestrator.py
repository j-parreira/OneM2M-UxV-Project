"""Benchmark orchestrator — runs one complete experiment scenario.

Manages the lifecycle of a single benchmark run:
  1. Instantiate and connect the correct ProtocolClient.
  2. Register callbacks to collect MetricRecords as messages arrive.
  3. Drive the scenario (send commands / wait for telemetry) for the run duration.
  4. Disconnect and return the collected records + run metadata.

Designed to be called from a background thread in the Streamlit benchmark page.
All cross-thread communication happens via threading.Event (stop_event) and a
callback queue passed in by the UI.

See docs/benchmark-flow.md and docs/ai-context/frontend-dev.md for the
full run flow and metric definitions.

Authors: João Parreira, Pedro Barbeiro
"""
import json
import queue
import threading
import time
from dataclasses import dataclass, asdict
from typing import Callable, Optional

from .config import Config
from .logger import MetricRecord, next_run_id, save_run
from .protocols.base import ProtocolClient
from .protocols.http_client import HttpClient
from .protocols.mqtt_client import MqttClient
from .protocols.websocket_client import WebSocketClient
from .protocols.coap_client import CoapClient


@dataclass
class RunConfig:
    """Parameters for a single benchmark run.

    run_id is auto-generated by next_run_id() if left empty.
    """
    protocol: str           # mqtt | http | websocket | coap
    scenario: int           # 1 | 2 | 3
    rate_msg_s: Optional[int]   # Scenario 1 only: 4 or 16 msg/s
    n_commands: int         # Scenario 2: 60; Scenario 1: rate × duration_s
    duration_s: int         # Scenario 1: 120 s; Scenario 2: from ack_run_timeout_s
    # Scenario 2: wall-clock cap for the entire burst.
    # Budget = n_commands × (per_cmd_ack_timeout + inter_command_delay_s).
    # 60 cmds × (10 s + 1 s) = 660 s worst case; 600 s is a safe ceiling for normal conditions.
    ack_run_timeout_s: int = 600
    # Scenario 2: delay between consecutive commands (ms), applied after each ACK.
    # 1000 ms ≈ 1 cmd/s; 60 cmds × 1 s ≈ 1 min per run.
    inter_command_delay_ms: int = 1000
    run_id: str = ""        # auto-generated if empty
    notes: str = ""         # operator notes for the JSON sidecar


@dataclass
class RunResult:
    """Returned by run() after a benchmark completes."""
    run_id: str
    records: list[MetricRecord]
    csv_path: str           # path to the written CSV file
    n_delivered: int
    n_total: int
    mean_latency_ms: Optional[float]


def _make_client(protocol: str, config: Config) -> ProtocolClient:
    """Instantiate the correct ProtocolClient for the given protocol string."""
    mapping = {
        "websocket": WebSocketClient,
        "mqtt": MqttClient,
        "http": HttpClient,
        "coap": CoapClient,
    }
    cls = mapping.get(protocol.lower())
    if cls is None:
        raise ValueError(f"Unknown protocol: {protocol!r}. Use one of {list(mapping)}")
    return cls(config)


def run(
    run_cfg: RunConfig,
    config: Config,
    stop_event: threading.Event,
    progress_cb: Optional[Callable[[int, int, list[MetricRecord]], None]] = None,
) -> RunResult:
    """Execute a complete benchmark run and write results to data/raw/.

    Parameters
    ----------
    run_cfg : RunConfig
    config : Config — connection parameters from .env
    stop_event : threading.Event — set by the UI to abort mid-run
    progress_cb : Optional callback invoked after each message, with
                  (n_delivered, n_total, records_so_far) for live UI updates.

    Returns
    -------
    RunResult
    """
    if not run_cfg.run_id:
        run_cfg.run_id = next_run_id(
            run_cfg.protocol, run_cfg.scenario, config.data_raw_dir, run_cfg.rate_msg_s,
        )

    client = _make_client(run_cfg.protocol, config)
    records: list[MetricRecord] = []
    records_lock = threading.Lock()
    n_total = 0
    n_delivered = 0

    # Capture run start time before any I/O for accurate sidecar reproducibility field.
    start_timestamp_ms = time.time_ns() // 1_000_000

    if run_cfg.scenario == 1:
        n_total = (run_cfg.rate_msg_s or 1) * run_cfg.duration_s
        records, n_delivered = _run_scenario_1(
            client, run_cfg, config, records_lock, stop_event, progress_cb
        )
    elif run_cfg.scenario == 2:
        n_total = run_cfg.n_commands
        records, n_delivered = _run_scenario_2(
            client, run_cfg, config, records_lock, stop_event, progress_cb
        )
    else:
        raise ValueError(f"Scenario {run_cfg.scenario} not implemented (3 is planned post-deadline)")

    csv_path = save_run(
        records=records,
        run_id=run_cfg.run_id,
        protocol=run_cfg.protocol,
        scenario=run_cfg.scenario,
        run_config_dict=asdict(run_cfg),
        data_raw_dir=config.data_raw_dir,
        notes=run_cfg.notes,
        start_timestamp_ms=start_timestamp_ms,
    )

    delivered_records = [r for r in records if r.delivered and r.latency_ms is not None]
    mean_lat = (
        sum(r.latency_ms for r in delivered_records) / len(delivered_records)
        if delivered_records else None
    )

    return RunResult(
        run_id=run_cfg.run_id,
        records=records,
        csv_path=str(csv_path),
        n_delivered=n_delivered,
        # Use the expected message count (not received) so loss % is meaningful.
        n_total=n_total,
        mean_latency_ms=mean_lat,
    )


