# Scenario implementations
# ------------------------------------------------------------------

def _run_scenario_1(
    client: ProtocolClient,
    run_cfg: RunConfig,
    config: Config,
    lock: threading.Lock,
    stop_event: threading.Event,
    progress_cb: Optional[Callable],
) -> tuple[list[MetricRecord], int]:
    """Scenario 1: passive telemetry collection over duration_s seconds.

    Steps:
      1. Connect + subscribe to telemetry
      2. Send setTelemetryRate command to configure the drone's emission rate
      3. Collect telemetry CINs until duration_s elapsed or stop_event set
      4. Disconnect

    Latency = timestamp_ms (Streamlit receive) - t_send_ms (Android send).
    NTP-dependent: both dev machine and RC must be NTP-synced on the same LAN.
    """
    records: list[MetricRecord] = []
    n_delivered = 0
    interval_ms = _rate_to_interval_ms(run_cfg.rate_msg_s or 1)

    tel_queue: queue.Queue = queue.Queue()

    def on_telemetry(con: dict) -> None:
        tel_queue.put((time.time_ns() // 1_000_000, con))

    client.subscribe_telemetry(on_telemetry)

    try:
        client.connect()

        # Ask Android to emit at the target rate.
        client.send_command({"command": "setTelemetryRate", "intervalMs": interval_ms})

        t_deadline = time.monotonic() + run_cfg.duration_s
        seq_local = 0

        while not stop_event.is_set() and time.monotonic() < t_deadline:
            try:
                timestamp_ms, con = tel_queue.get(timeout=1.0)
            except queue.Empty:
                continue

            seq_local += 1
            android_seq = con.get("seq", seq_local)
            t_send_ms = con.get("t_send_ms")
            payload_str = json.dumps(con)
            payload_bytes = len(payload_str.encode())
            header_bytes = client.get_header_bytes(payload_bytes)

            # Latency is NTP-dependent: both devices must be synced to the same clock.
            # Raw delta is kept (can be negative) — negative values indicate the Android
            # clock is ahead of the dev-machine clock (clock offset, not real latency).
            # Do NOT clamp to 0 here: the raw value is needed to detect/correct the offset
            # in the analysis phase. Document the NTP dependency in the paper methodology.
            latency_ms: Optional[float] = None
            if t_send_ms is not None:
                raw_delta = timestamp_ms - t_send_ms
                latency_ms = float(raw_delta)
                # Log first 3 packets per run to diagnose clock offset
                if seq_local <= 3:
                    print(
                        f"[{time.strftime('%H:%M:%S')}][S1] seq={android_seq} t_send_ms={t_send_ms} "
                        f"timestamp_ms={timestamp_ms} delta={raw_delta:+.0f} ms",
                        flush=True,
                    )

            rec = MetricRecord(
                timestamp_ms=timestamp_ms,
                run_id=run_cfg.run_id,
                protocol=run_cfg.protocol,
                scenario=1,
                direction="telemetry",
                latency_ms=latency_ms,
                payload_bytes=payload_bytes,
                header_bytes=header_bytes,
                delivered=True,
                seq=android_seq,
                t_send_ms=t_send_ms,
                t_cmd_ms=None,
                t_recv_ms=None,
                t_exec_ms=None,
                cin_create_ms=None,  # telemetry rows: no command sent from Streamlit
            )
            with lock:
                records.append(rec)
                n_delivered += 1

            if progress_cb:
                progress_cb(n_delivered, n_delivered, list(records))

    finally:
        # Pause Android telemetry before disconnect so the CSE event loop is not
        # further saturated between runs. No recovery wait here — the next run
        # measures raw CSE performance including any residual TinyDB queue backlog.
        try:
            client.send_command({"command": "setTelemetryRate", "intervalMs": 60000})
        except Exception:
            pass
        client.disconnect()

    return records, n_delivered


def _run_scenario_2(
    client: ProtocolClient,
    run_cfg: RunConfig,
    config: Config,
    lock: threading.Lock,
    stop_event: threading.Event,
    progress_cb: Optional[Callable],
) -> tuple[list[MetricRecord], int]:
    """Scenario 2: send n_commands commands at a fixed inter-command delay.

    Commands rotate through a 4-step cycle:
      1. takeoff
      2. identify (state=True  — lights on)
      3. land
      4. identify (state=False — lights off)

    Waits for the ACK of each command before sleeping inter_command_delay_ms
    and sending the next. The cycle repeats for the full n_commands burst.

    Latency = t_recv_ms - t_cmd_ms (NTP-dependent: Streamlit and Android clocks).
    """
    records: list[MetricRecord] = []
    n_delivered = 0

    # Scenario 3 (paper) measures pure protocol latency — ping has no DJI SDK action,
    # so ACK is immediate and latency reflects only protocol + middleware overhead.
    _CMD_CYCLE = [{"command": "ping"}]

    ack_queue: queue.Queue = queue.Queue()

    def on_ack(con: dict) -> None:
        ack_queue.put(con)

    client.subscribe_ack(on_ack)

    try:
        client.connect()

        # Reduce telemetry to near-zero before the command burst.
        # At 4 msg/s, concurrent telemetry CIN writes block the CSE asyncio event loop
        # (TinyDB is synchronous), causing ACK notification delays of 10–30 s.
        # S3 measures command latency with no background load — stopping telemetry
        # is semantically appropriate and eliminates this source of packet loss.
        client.send_command({"command": "setTelemetryRate", "intervalMs": 60000})
        # No recovery wait — start the burst immediately to measure raw CSE performance.
        # If a prior S1 at 16 msg/s left the TinyDB queue backlogged, the first commands
        # will show elevated cin_create_ms (6–7 s observed) and possible ACK timeouts.
        # This is intentional: the data captures the CSE's actual recovery behaviour.
        # Drain the setup command's ACK (seq_cmd defaults to 0 on Android) so the
        # main loop doesn't see a spurious entry while waiting for seq_cmd=1.
        while True:
            try:
                ack_queue.get_nowait()
            except queue.Empty:
                break

        # Start the run clock AFTER setup so the 600 s budget is spent on commands only.
        run_deadline = time.monotonic() + run_cfg.ack_run_timeout_s

        for seq_cmd in range(1, run_cfg.n_commands + 1):
            if stop_event.is_set():
                break
            if time.monotonic() >= run_deadline:
                print(
                    f"[{time.strftime('%H:%M:%S')}][S2] run timeout ({run_cfg.ack_run_timeout_s}s) reached after "
                    f"{seq_cmd - 1}/{run_cfg.n_commands} commands — aborting burst",
                    flush=True,
                )
                break

            base_cmd = _CMD_CYCLE[(seq_cmd - 1) % len(_CMD_CYCLE)]
            t_cmd_ms = int(time.time() * 1000)
            payload = {
                **base_cmd,
                "seq_cmd": seq_cmd,
                "t_cmd_ms": t_cmd_ms,
            }
            payload_str = json.dumps(payload)
            payload_bytes = len(payload_str.encode())

            send_latency_ms, send_ok = client.send_command(payload)
            header_bytes = client.get_header_bytes(payload_bytes)
            timestamp_ms = time.time_ns() // 1_000_000

            if not send_ok:
                # CIN creation failed — record as undelivered; no ACK possible.
                rec = MetricRecord(
                    timestamp_ms=timestamp_ms,
                    run_id=run_cfg.run_id,
                    protocol=run_cfg.protocol,
                    scenario=2,
                    direction="command",
                    latency_ms=None,
                    payload_bytes=payload_bytes,
                    header_bytes=header_bytes,
                    delivered=False,
                    seq=seq_cmd,
                    t_send_ms=None,
                    t_cmd_ms=t_cmd_ms,
                    t_recv_ms=None,
                    t_exec_ms=None,
                    cin_create_ms=None,  # failed — no round-trip time available
                )
                with lock:
                    records.append(rec)
                continue

            # CIN creation succeeded: record the Streamlit→CSE round-trip separately.
            cin_create_ms: Optional[float] = send_latency_ms

            # Per-command ACK timeout, clamped to the remaining run budget so the
            # overall ack_run_timeout_s is always respected.
            # Drain the queue until the matching seq_cmd arrives or time runs out.
            # A single get() is not enough: a late ACK from a previous command can
            # contaminate the queue and cause a cascade of false misses.
            remaining_s = max(0.0, run_deadline - time.monotonic())
            ack_deadline = time.monotonic() + min(10.0, remaining_s)
            ack_con = None
            while time.monotonic() < ack_deadline:
                try:
                    candidate = ack_queue.get(timeout=max(0.0, ack_deadline - time.monotonic()))
                    if candidate.get("seq_cmd") == seq_cmd:
                        ack_con = candidate
                        break
                    # Stale/mismatched ACK — discard and keep waiting
                    print(
                        f"[{time.strftime('%H:%M:%S')}][S2] discarded stale ACK seq_cmd={candidate.get('seq_cmd')} "
                        f"(waiting for {seq_cmd})",
                        flush=True,
                    )
                except queue.Empty:
                    break

            if ack_con:
                t_recv_ms = ack_con.get("t_recv_ms")
                t_exec_ms = ack_con.get("t_exec_ms")
                # End-to-end latency: Android receive minus Streamlit send (NTP-dependent).
                # Negative values indicate the RC clock is behind the dev-machine clock
                # (clock offset, not real negative latency). Raw value kept so the analysis
                # phase can detect and correct the offset. Typical offset ≈ −1.88 s.
                # Null when t_recv_ms not returned — do NOT fall back to cin_create_ms,
                # which measures a different path (Streamlit→CSE only).
                latency_ms: Optional[float] = (
                    (t_recv_ms - t_cmd_ms) if t_recv_ms is not None else None
                )
                delivered = True
                n_delivered += 1
            else:
                t_recv_ms = None
                t_exec_ms = None
                latency_ms = None   # ACK timeout — no end-to-end measurement
                delivered = False

            rec = MetricRecord(
                timestamp_ms=timestamp_ms,
                run_id=run_cfg.run_id,
                protocol=run_cfg.protocol,
                scenario=2,
                direction="command",
                latency_ms=latency_ms,
                payload_bytes=payload_bytes,
                header_bytes=header_bytes,
                delivered=delivered,
                seq=seq_cmd,
                t_send_ms=None,
                t_cmd_ms=t_cmd_ms,
                t_recv_ms=t_recv_ms,
                t_exec_ms=t_exec_ms,
                cin_create_ms=cin_create_ms,
            )
            with lock:
                records.append(rec)

            if progress_cb:
                progress_cb(n_delivered, seq_cmd, list(records))

            if run_cfg.inter_command_delay_ms > 0:
                time.sleep(run_cfg.inter_command_delay_ms / 1000.0)

    finally:
        client.disconnect()

    return records, n_delivered


def _rate_to_interval_ms(rate_msg_s: int) -> int:
    """Convert msg/s rate to intervalMs for the setTelemetryRate command.

    Floor at 50 ms (20 msg/s) — below that, Android SDK scheduling jitter
    makes the rate unreliable. Benchmark uses 4 msg/s (250 ms) and 16 msg/s (62 ms).
    """
    return max(50, 1000 // rate_msg_s)
